const Z_LEVELS = [-3, -2, -1, 0, 1, 2, 3];

// Compute BMI-for-age z-score using WHO 2007 reference (SD-based interpolation)
export function computeZScore(sex, ageMonths, bmi) {
  if (!sex || ageMonths == null || bmi == null || bmi <= 0) return null;
  const data = sex === "male" ? WHO_BOYS : WHO_GIRLS;
  if (!data || data.length === 0) return null;

  let age = ageMonths;
  if (age < data[0][0]) age = data[0][0];
  if (age > data[data.length - 1][0]) age = data[data.length - 1][0];

  let lo = data[0];
  let hi = data[data.length - 1];
  for (let i = 0; i < data.length - 1; i++) {
    if (data[i][0] <= age && data[i + 1][0] >= age) {
      lo = data[i];
      hi = data[i + 1];
      break;
    }
  }

  const t = hi[0] === lo[0] ? 0 : (age - lo[0]) / (hi[0] - lo[0]);
  const bmiAtSd = Z_LEVELS.map((_, i) => lo[i + 1] + t * (hi[i + 1] - lo[i + 1]));

  if (bmi <= bmiAtSd[0]) {
    const gap = bmiAtSd[1] - bmiAtSd[0];
    return gap > 0 ? -3 - (bmiAtSd[0] - bmi) / gap : -3;
  }
  if (bmi >= bmiAtSd[6]) {
    const gap = bmiAtSd[6] - bmiAtSd[5];
    return gap > 0 ? 3 + (bmi - bmiAtSd[6]) / gap : 3;
  }

  for (let i = 0; i < 6; i++) {
    if (bmi >= bmiAtSd[i] && bmi <= bmiAtSd[i + 1]) {
      const frac = bmiAtSd[i + 1] - bmiAtSd[i] > 0
        ? (bmi - bmiAtSd[i]) / (bmiAtSd[i + 1] - bmiAtSd[i])
        : 0;
      return Z_LEVELS[i] + frac * (Z_LEVELS[i + 1] - Z_LEVELS[i]);
    }
  }
  return null;
}

export function nutritionalStatusFromZScore(z) {
  if (z == null || isNaN(z)) return "Chờ dữ liệu tham chiếu WHO";
  if (z < -3) return "Gầy còm nặng";
  if (z < -2) return "Gầy còm";
  if (z <= 1) return "Bình thường";
  if (z <= 2) return "Thừa cân";
  return "Béo phì";
}